const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { supabase } = require('./_lib/supabase');
const { sendTemplate } = require('./_lib/whatsapp');
const { PROGRAM_NAMES, maskPhone, cors, parseBody } = require('./_lib/utils');

const MADDY_PHONE = process.env.MADDY_PHONE || '+917082478374';

const SAFETY_FLAGS = [
  'below 1000 calories', 'under 800 cal', 'extreme deficit',
  'clenbuterol', 'dnp', 'sarms', 'steroids', 'anabolic',
  'lose 10kg in 1 week', 'lose 20 pounds in',
];

function hasSafetyIssue(text) {
  const lower = (text || '').toLowerCase();
  return SAFETY_FLAGS.some(f => lower.includes(f));
}

async function generatePDF(client, weekNo, workout, nutrition, notes) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header bar
    doc.rect(0, 0, 595, 80).fill('#2C2C2C');
    doc.fontSize(28).fill('#B8965A').font('Helvetica-Bold')
      .text('FITNESS BY MADDY', 50, 25, { width: 495 });
    doc.fontSize(10).fill('#FFFFFF').font('Helvetica')
      .text(`WEEK ${weekNo} PROGRAM`, 50, 55, { width: 495 });

    doc.moveDown(3);
    doc.fill('#2C2C2C');

    // Client info
    doc.fontSize(12).font('Helvetica-Bold')
      .text(`Client: ${client.name || 'Client'}`, 50);
    doc.fontSize(10).font('Helvetica')
      .text(`Program: ${PROGRAM_NAMES[client.program] || client.program}`)
      .text(`Week: ${weekNo}`)
      .text(`Generated: ${new Date().toLocaleDateString('en-IN')}`);

    doc.moveDown(1.5);
    doc.rect(50, doc.y, 495, 1).fill('#B8965A');
    doc.moveDown(1);

    // Workout Plan
    doc.fill('#2C2C2C');
    doc.fontSize(16).font('Helvetica-Bold').text('WORKOUT PLAN');
    doc.moveDown(0.5);
    doc.fontSize(10).font('Helvetica');

    if (workout && typeof workout === 'object') {
      for (const [day, exercises] of Object.entries(workout)) {
        doc.moveDown(0.3);
        doc.font('Helvetica-Bold').text(day.toUpperCase(), { underline: true });
        doc.font('Helvetica');
        if (Array.isArray(exercises)) {
          exercises.forEach(ex => {
            const line = typeof ex === 'string' ? ex
              : `${ex.name} — ${ex.sets}x${ex.reps}${ex.rest ? ` (Rest: ${ex.rest})` : ''}`;
            doc.text(`  ${line}`);
          });
        } else {
          doc.text(`  ${String(exercises)}`);
        }
      }
    } else {
      doc.text(String(workout || 'See your coach for details.'));
    }

    doc.moveDown(1.5);
    doc.rect(50, doc.y, 495, 1).fill('#B8965A');
    doc.moveDown(1);

    // Nutrition Plan
    doc.fill('#2C2C2C');
    doc.fontSize(16).font('Helvetica-Bold').text('NUTRITION PLAN');
    doc.moveDown(0.5);
    doc.fontSize(10).font('Helvetica');

    if (nutrition && typeof nutrition === 'object') {
      if (nutrition.calories) doc.text(`Daily Calories: ${nutrition.calories} kcal`);
      if (nutrition.protein) doc.text(`Protein: ${nutrition.protein}g`);
      if (nutrition.carbs) doc.text(`Carbs: ${nutrition.carbs}g`);
      if (nutrition.fat) doc.text(`Fat: ${nutrition.fat}g`);
      doc.moveDown(0.5);
      if (nutrition.meals && Array.isArray(nutrition.meals)) {
        nutrition.meals.forEach((meal, i) => {
          doc.font('Helvetica-Bold').text(`Meal ${i + 1}: ${meal.name || ''}`);
          doc.font('Helvetica').text(`  ${meal.description || meal.items || ''}`);
        });
      }
      if (nutrition.notes) {
        doc.moveDown(0.5);
        doc.text(`Notes: ${nutrition.notes}`);
      }
    } else {
      doc.text(String(nutrition || 'See your coach for details.'));
    }

    if (notes) {
      doc.moveDown(1);
      doc.rect(50, doc.y, 495, 1).fill('#B8965A');
      doc.moveDown(1);
      doc.fill('#2C2C2C');
      doc.fontSize(12).font('Helvetica-Bold').text('COACH NOTES');
      doc.moveDown(0.3);
      doc.fontSize(10).font('Helvetica').text(notes);
    }

    // Footer
    doc.moveDown(2);
    doc.fontSize(8).fill('#999999')
      .text('This program is generated by Fitness by Maddy. Follow the plan as prescribed. If you experience pain or discomfort, stop and consult your coach.', 50, undefined, { width: 495, align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  cors(res);
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });

  try {
    const body = await parseBody(req);
    const { client_id, week_no } = body;

    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'Missing client_id or week_no' });
    }

    const { data: client } = await supabase
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) return res.status(404).json({ error: 'Client not found' });

    const { data: recentCheckins } = await supabase
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    const { data: prevPrograms } = await supabase
      .from('programs')
      .select('workout_plan, nutrition_plan, notes')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(1);

    const anthropic = new Anthropic();
    const checkinSummary = (recentCheckins || []).map(c =>
      `Week ${c.week_no}: weight=${c.weight}kg, waist=${c.waist}cm, compliance=${c.compliance_score}/10, energy=${c.energy}/10, issues="${c.issues || 'none'}"`
    ).join('\n');

    const prevPlan = prevPrograms?.[0]
      ? `Previous workout: ${JSON.stringify(prevPrograms[0].workout_plan)}\nPrevious nutrition: ${JSON.stringify(prevPrograms[0].nutrition_plan)}`
      : 'No previous plan (Week 1).';

    const prompt = `You are a certified personal trainer and nutrition coach creating a weekly program for a client.

CLIENT PROFILE:
- Name: ${client.name || 'Client'}
- Program: ${PROGRAM_NAMES[client.program] || client.program}
- Week: ${week_no}

RECENT CHECK-INS:
${checkinSummary || 'No check-ins yet (first week).'}

PREVIOUS PLAN:
${prevPlan}

Create Week ${week_no}'s workout and nutrition plan. Return valid JSON with this structure:
{
  "workout": {
    "monday": [{"name": "Exercise", "sets": 3, "reps": "10-12", "rest": "60s"}],
    "tuesday": [...],
    ...
  },
  "nutrition": {
    "calories": 2000,
    "protein": 150,
    "carbs": 200,
    "fat": 70,
    "meals": [{"name": "Breakfast", "description": "..."}],
    "notes": "..."
  },
  "coach_notes": "Brief note about this week's focus and adjustments."
}

Rules:
- Progressive overload from previous week where applicable
- Adjust based on check-in compliance and energy levels
- Never prescribe below 1200 calories for women or 1500 for men
- No banned substances or supplements requiring prescription
- Keep it practical and achievable
- If energy was low, reduce volume slightly and add deload sets
- Return ONLY the JSON, no other text`;

    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 4000,
      messages: [{ role: 'user', content: prompt }],
    });

    const rawText = response.content[0].text;

    if (hasSafetyIssue(rawText)) {
      await supabase.from('messages').insert({
        phone: MADDY_PHONE,
        direction: 'out',
        body: `SAFETY FLAG: Program for ${maskPhone(client.phone)} Week ${week_no} flagged for review. Raw output stored but NOT sent.`,
      });
      return res.json({ ok: false, reason: 'safety_flagged' });
    }

    let parsed;
    try {
      const jsonMatch = rawText.match(/\{[\s\S]*\}/);
      parsed = JSON.parse(jsonMatch ? jsonMatch[0] : rawText);
    } catch {
      console.error('Failed to parse Claude response as JSON');
      return res.status(500).json({ error: 'Invalid AI response format' });
    }

    const pdfBuffer = await generatePDF(
      client, week_no,
      parsed.workout, parsed.nutrition, parsed.coach_notes
    );

    const filePath = `${client.id}/week_${week_no}.pdf`;
    const { error: uploadError } = await supabase.storage
      .from('clients')
      .upload(filePath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true,
      });

    if (uploadError) {
      console.error('PDF upload failed:', uploadError.message);
    }

    const { data: urlData } = supabase.storage
      .from('clients')
      .getPublicUrl(filePath);

    const pdfUrl = urlData?.publicUrl || filePath;

    const { data: program } = await supabase.from('programs').insert({
      client_id,
      week_no: parseInt(week_no),
      pdf_url: pdfUrl,
      workout_plan: parsed.workout,
      nutrition_plan: parsed.nutrition,
      notes: parsed.coach_notes,
    }).select().single();

    await sendTemplate(client.phone, 'weekly_program', [
      client.name || 'there',
      String(week_no),
      parsed.coach_notes || 'New week, new gains!',
    ]);

    await supabase.from('programs')
      .update({ whatsapp_sent_at: new Date().toISOString() })
      .eq('id', program.id);

    return res.json({ ok: true, program_id: program.id, pdf_url: pdfUrl });
  } catch (err) {
    console.error('generate-program error:', err.message);
    return res.status(500).json({ error: 'Internal error' });
  }
};
