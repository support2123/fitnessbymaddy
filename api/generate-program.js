const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { getSupabase } = require('../lib/supabase');
const { sendTemplate } = require('../lib/whatsapp');
const { maskPhone, isHinglish, detectMarket } = require('../lib/market');

const SAFETY_FLAGS = [
  'extreme calorie', 'below 1000', 'below 800', 'starvation',
  'banned substance', 'steroid', 'ephedra', 'dnp', 'clenbuterol',
  'lose 10kg in 1 week', 'lose 20 pounds in',
];

function hasSafetyIssue(text) {
  const lower = text.toLowerCase();
  return SAFETY_FLAGS.some(flag => lower.includes(flag));
}

async function generatePDF(workoutPlan, nutritionPlan, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 120).fill('#2C2C2C');
    doc.fill('#B8965A').fontSize(28).font('Helvetica-Bold')
      .text('FITNESS BY MADDY', 50, 35, { align: 'center' });
    doc.fill('#FFFFFF').fontSize(14).font('Helvetica')
      .text(`Week ${weekNo} Program — ${clientName || 'Client'}`, 50, 75, { align: 'center' });

    doc.moveDown(3);
    doc.fill('#2C2C2C').fontSize(20).font('Helvetica-Bold').text('WORKOUT PLAN');
    doc.moveDown(0.5);
    doc.fill('#6B6B6B').fontSize(11).font('Helvetica');

    if (workoutPlan && workoutPlan.days) {
      for (const day of workoutPlan.days) {
        doc.moveDown(0.5);
        doc.fill('#B8965A').fontSize(13).font('Helvetica-Bold').text(day.name || 'Training Day');
        doc.fill('#2C2C2C').fontSize(10).font('Helvetica');
        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.text(`  •  ${ex.name} — ${ex.sets || '3'} x ${ex.reps || '12'} ${ex.notes ? `(${ex.notes})` : ''}`, { indent: 20 });
          }
        }
      }
    } else if (typeof workoutPlan === 'string') {
      doc.text(workoutPlan);
    }

    doc.moveDown(2);
    doc.fill('#2C2C2C').fontSize(20).font('Helvetica-Bold').text('NUTRITION PLAN');
    doc.moveDown(0.5);

    if (nutritionPlan && nutritionPlan.meals) {
      for (const meal of nutritionPlan.meals) {
        doc.moveDown(0.3);
        doc.fill('#B8965A').fontSize(12).font('Helvetica-Bold').text(meal.name || 'Meal');
        doc.fill('#2C2C2C').fontSize(10).font('Helvetica');
        if (meal.items) {
          for (const item of meal.items) {
            doc.text(`  •  ${item}`, { indent: 20 });
          }
        }
        if (meal.macros) {
          doc.fill('#6B6B6B').fontSize(9).text(`     ${meal.macros}`, { indent: 20 });
        }
      }
      if (nutritionPlan.daily_totals) {
        doc.moveDown(1);
        doc.fill('#2C2C2C').fontSize(11).font('Helvetica-Bold').text(`Daily Totals: ${nutritionPlan.daily_totals}`);
      }
    } else if (typeof nutritionPlan === 'string') {
      doc.text(nutritionPlan);
    }

    if (nutritionPlan && nutritionPlan.notes) {
      doc.moveDown(1);
      doc.fill('#6B6B6B').fontSize(10).font('Helvetica').text(`Note: ${nutritionPlan.notes}`);
    }

    doc.moveDown(3);
    doc.fill('#E8E3DC').rect(50, doc.y, doc.page.width - 100, 1).fill();
    doc.moveDown(0.5);
    doc.fill('#B8965A').fontSize(9).font('Helvetica')
      .text('Generated by Fitness by Maddy coaching system. For personal use only.', { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const authHeader = req.headers['authorization'];
  if (authHeader !== `Bearer ${process.env.INTERNAL_API_KEY}`) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  try {
    const { client_id, week_no } = req.body;
    if (!client_id || !week_no) return res.status(400).json({ error: 'Missing client_id or week_no' });

    const db = getSupabase();

    const { data: client } = await db
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) return res.status(404).json({ error: 'Client not found' });

    const { data: recentCheckins } = await db
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    let intakeData = {};
    if (client.lead_id) {
      const { data: lead } = await db.from('leads').select('first_msg').eq('id', client.lead_id).single();
      if (lead && lead.first_msg) {
        try { intakeData = JSON.parse(lead.first_msg); } catch (e) { intakeData = { note: lead.first_msg }; }
      }
    }

    const anthropic = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });

    const systemPrompt = `You are a program architect for Fitness by Maddy, an elite online fitness coaching brand.
Generate a personalized weekly workout and nutrition plan.
Output ONLY valid JSON with this structure:
{
  "workout_plan": {
    "days": [
      {
        "name": "Day 1 — Upper Body Push",
        "exercises": [
          { "name": "Barbell Bench Press", "sets": "4", "reps": "8-10", "notes": "Control eccentric" }
        ]
      }
    ],
    "notes": "Optional weekly workout note"
  },
  "nutrition_plan": {
    "meals": [
      { "name": "Meal 1 — Breakfast", "items": ["3 eggs scrambled", "2 toast"], "macros": "P: 25g | C: 30g | F: 15g" }
    ],
    "daily_totals": "Calories: 2000 | P: 160g | C: 200g | F: 65g",
    "notes": "Optional note"
  },
  "context_note": "One line summary for WhatsApp"
}
Be specific with exercises, sets, reps. Tailor to the client's level, goals, and any reported issues. Use progressive overload from previous weeks.
Never suggest extreme caloric restriction (below 1200 for women, below 1500 for men). Never recommend banned or unsafe substances.`;

    const userPrompt = `Client: ${client.name || 'Anonymous'}
Program: ${client.program}
Week: ${week_no}
Profile: ${JSON.stringify(intakeData)}
Recent check-ins: ${JSON.stringify(recentCheckins || [])}

Generate Week ${week_no} program.`;

    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      system: systemPrompt,
      messages: [{ role: 'user', content: userPrompt }],
    });

    const rawText = response.content[0].text;

    if (hasSafetyIssue(rawText)) {
      const { notifyMaddy } = require('../lib/whatsapp');
      await notifyMaddy('Program safety flag', `Client: ${maskPhone(client.phone)}\nWeek ${week_no}\nFlagged content detected — review needed`);
      return res.status(200).json({ action: 'flagged_for_review', client_id });
    }

    let parsed;
    try {
      const jsonMatch = rawText.match(/\{[\s\S]*\}/);
      parsed = JSON.parse(jsonMatch ? jsonMatch[0] : rawText);
    } catch (parseErr) {
      console.error('Failed to parse Claude response for client', client_id);
      return res.status(500).json({ error: 'Failed to parse program' });
    }

    const { workout_plan, nutrition_plan, context_note } = parsed;

    const pdfBuffer = await generatePDF(workout_plan, nutrition_plan, client.name, week_no);

    const pdfPath = `${client.folder_url || `clients/${client_id}`}/week_${week_no}.pdf`;
    const { error: uploadErr } = await db.storage
      .from('clients')
      .upload(pdfPath, pdfBuffer, { contentType: 'application/pdf', upsert: true });

    if (uploadErr) {
      console.error('PDF upload failed:', uploadErr.message);
    }

    const { data: urlData } = db.storage.from('clients').getPublicUrl(pdfPath);
    const pdfUrl = urlData?.publicUrl || pdfPath;

    const { data: program, error: progErr } = await db.from('programs').insert({
      client_id,
      week_no,
      pdf_url: pdfUrl,
      workout_plan,
      nutrition_plan,
      notes: context_note || null,
    }).select().single();

    if (progErr) {
      console.error('Program insert failed:', progErr.message);
      return res.status(500).json({ error: 'Failed to save program' });
    }

    const market = detectMarket(client.phone);
    const templateName = isHinglish(market) ? 'weekly_program_hi' : 'weekly_program_en';
    await sendTemplate(client.phone, templateName, [
      client.name || 'there',
      `Week ${week_no}`,
      context_note || 'Your new program is ready!',
      pdfUrl,
    ], client.name);

    await db.from('programs').update({ whatsapp_sent_at: new Date().toISOString() }).eq('id', program.id);

    return res.status(200).json({ success: true, program_id: program.id, pdf_url: pdfUrl });
  } catch (err) {
    console.error('Generate program error:', err.message);
    return res.status(500).json({ error: 'Internal error' });
  }
};
