const { supabase } = require('./lib/supabase');
const { sendTemplate, maskPhone } = require('./lib/whatsapp');
const { escalateToMaddy } = require('./lib/escalation');
const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');

const claude = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });

const RISKY_PATTERNS = [
  /under\s*1[0-2]00\s*cal/i,
  /starvation/i,
  /clenbuterol|dnp|ephedra|sarm/i,
  /lose\s*\d{2,}\s*(kg|lb|pound).*week/i
];

function hasSafetyIssue(text) {
  return RISKY_PATTERNS.some(p => p.test(text));
}

async function generatePDF(client, weekNo, workout, nutrition, notes) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 40 });
    const chunks = [];

    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 100).fill('#1a1a1a');
    doc.fontSize(28).fill('#D4AF7A').font('Helvetica-Bold')
      .text('FITNESS BY MADDY', 40, 30);
    doc.fontSize(14).fill('#ffffff').font('Helvetica')
      .text(`Week ${weekNo} Program — ${client.name || 'Client'}`, 40, 65);

    doc.moveDown(3);

    doc.fontSize(18).fill('#1a1a1a').font('Helvetica-Bold')
      .text('WORKOUT PLAN', 40);
    doc.moveDown(0.5);
    doc.moveTo(40, doc.y).lineTo(555, doc.y).stroke('#D4AF7A');
    doc.moveDown(0.5);

    if (workout && workout.days) {
      for (const day of workout.days) {
        doc.fontSize(13).fill('#1a1a1a').font('Helvetica-Bold')
          .text(day.name || day.day, 40);
        doc.moveDown(0.3);
        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.fontSize(10).fill('#333333').font('Helvetica')
              .text(`  • ${ex.name}: ${ex.sets || ''}x${ex.reps || ''} ${ex.notes || ''}`, 50);
          }
        }
        doc.moveDown(0.5);
      }
    } else {
      doc.fontSize(10).fill('#333').font('Helvetica')
        .text(JSON.stringify(workout, null, 2), 50, doc.y, { width: 500 });
    }

    if (doc.y > 650) doc.addPage();
    doc.moveDown(1);

    doc.fontSize(18).fill('#1a1a1a').font('Helvetica-Bold')
      .text('NUTRITION PLAN', 40);
    doc.moveDown(0.5);
    doc.moveTo(40, doc.y).lineTo(555, doc.y).stroke('#D4AF7A');
    doc.moveDown(0.5);

    if (nutrition && nutrition.meals) {
      for (const meal of nutrition.meals) {
        doc.fontSize(12).fill('#1a1a1a').font('Helvetica-Bold')
          .text(meal.name || meal.meal, 40);
        doc.fontSize(10).fill('#333').font('Helvetica')
          .text(meal.description || meal.items?.join(', ') || '', 50);
        if (meal.macros) {
          doc.fontSize(9).fill('#666').font('Helvetica')
            .text(`Macros: ${meal.macros}`, 50);
        }
        doc.moveDown(0.4);
      }
    } else {
      doc.fontSize(10).fill('#333').font('Helvetica')
        .text(JSON.stringify(nutrition, null, 2), 50, doc.y, { width: 500 });
    }

    if (notes) {
      if (doc.y > 700) doc.addPage();
      doc.moveDown(1);
      doc.fontSize(12).fill('#1a1a1a').font('Helvetica-Bold').text('NOTES', 40);
      doc.fontSize(10).fill('#333').font('Helvetica').text(notes, 50);
    }

    doc.moveDown(2);
    doc.fontSize(8).fill('#999').font('Helvetica')
      .text('Generated by FitnessByMaddy Coaching Platform. For personal use only.', 40, doc.page.height - 40, { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });

  try {
    const { client_id, week_no } = req.body;
    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'client_id and week_no required' });
    }

    const { data: client } = await supabase
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) return res.status(404).json({ error: 'Client not found' });

    const { data: recentCheckins } = await supabase
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    let intakeData = null;
    try {
      const { data: intakeFile } = await supabase.storage
        .from('clients')
        .download(`clients/${client.lead_id || client_id}/intake.json`);
      if (intakeFile) {
        intakeData = JSON.parse(await intakeFile.text());
      }
    } catch (_) {}

    const checkinSummary = (recentCheckins || []).map(c => ({
      week: c.week_no,
      weight: c.weight,
      waist: c.waist,
      compliance: c.compliance_score,
      energy: c.energy,
      issues: c.issues
    }));

    const systemPrompt = `You are a NASM-certified fitness program architect for FitnessByMaddy.
Create a personalized weekly training and nutrition program.

RULES:
- Science-backed, safe programming only
- No extreme calorie deficits (never below 1200 cal for women, 1500 for men)
- No banned substances or supplements with safety concerns
- Progressive overload principles
- Account for injuries, limitations, and reported issues
- Be specific: exact exercises, sets, reps, rest periods
- Nutrition: specific meals, portions, macros

Output ONLY valid JSON with this structure:
{
  "workout": {
    "days": [
      {
        "name": "Day 1 - Upper Body",
        "exercises": [
          {"name": "Bench Press", "sets": 4, "reps": "8-10", "rest": "90s", "notes": ""}
        ]
      }
    ]
  },
  "nutrition": {
    "calories": 1800,
    "protein": 140,
    "carbs": 180,
    "fat": 60,
    "meals": [
      {"name": "Meal 1 - Breakfast", "description": "...", "macros": "P:35g C:40g F:12g"}
    ]
  },
  "notes": "One-liner weekly focus or encouragement"
}`;

    const userPrompt = `Client: ${client.name || 'Client'}
Program: ${client.program}
Week: ${week_no} of ${client.program === '12wk' ? 12 : 6}

${intakeData ? `Intake Profile: ${JSON.stringify(intakeData)}` : 'No intake data available.'}

Recent Check-ins: ${checkinSummary.length > 0 ? JSON.stringify(checkinSummary) : 'First week — no check-in data yet.'}

Generate the Week ${week_no} program.`;

    const response = await claude.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      system: systemPrompt,
      messages: [{ role: 'user', content: userPrompt }]
    });

    const rawContent = response.content[0].text;

    if (hasSafetyIssue(rawContent)) {
      await escalateToMaddy('Risky program content flagged', {
        phone: maskPhone(client.phone),
        details: `Week ${week_no} for ${client.name} — auto-halted for review`
      });
      return res.json({ ok: false, reason: 'safety_review', flagged: true });
    }

    const jsonMatch = rawContent.match(/\{[\s\S]*\}/);
    if (!jsonMatch) {
      return res.status(500).json({ error: 'Failed to parse program JSON' });
    }

    const program = JSON.parse(jsonMatch[0]);
    const { workout, nutrition, notes } = program;

    const pdfBuffer = await generatePDF(client, week_no, workout, nutrition, notes);

    const pdfPath = `clients/${client_id}/week_${week_no}.pdf`;
    await supabase.storage.from('clients').upload(pdfPath, pdfBuffer, {
      contentType: 'application/pdf',
      upsert: true
    });

    const { data: urlData } = supabase.storage.from('clients').getPublicUrl(pdfPath);
    const pdfUrl = urlData.publicUrl;

    const { error: dbError } = await supabase.from('programs').upsert({
      client_id,
      week_no: parseInt(week_no),
      generated_at: new Date().toISOString(),
      pdf_url: pdfUrl,
      workout_plan: workout,
      nutrition_plan: nutrition,
      notes
    }, { onConflict: 'client_id,week_no' });

    if (dbError) throw dbError;

    await sendTemplate(client.phone, 'weekly_program', {
      name: client.name || 'there',
      templateParams: [
        client.name || 'there',
        String(week_no)
      ],
      media: { url: pdfUrl, filename: `Week_${week_no}_Program.pdf` }
    });

    await supabase.from('programs').update({
      whatsapp_sent_at: new Date().toISOString()
    }).eq('client_id', client_id).eq('week_no', parseInt(week_no));

    return res.json({ ok: true, pdf_url: pdfUrl, week_no });
  } catch (err) {
    console.error('Program generation error:', err.message);
    return res.status(500).json({ error: 'Internal error' });
  }
};
