const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { getSupabase } = require('./_lib/supabase');
const { sendTemplate } = require('./_lib/whatsapp');
const { detectMarket, isHinglish, maskPhone } = require('./_lib/market');
const { escalateToMaddy } = require('./_lib/escalation');

const RISKY_KEYWORDS = [
  'extreme calorie', 'below 1000', 'below 800', 'starvation',
  'clenbuterol', 'dnp', 'ephedrine', 'anabolic', 'steroid',
  'lose 10kg in 1 week', 'crash diet', 'water fast'
];

function hasDangerousContent(text) {
  const lower = text.toLowerCase();
  return RISKY_KEYWORDS.some(kw => lower.includes(kw));
}

async function generatePDF(workoutPlan, nutritionPlan, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(28).font('Helvetica-Bold')
      .fillColor('#2C2C2C')
      .text('FITNESS BY MADDY', { align: 'center' });

    doc.moveDown(0.5);
    doc.fontSize(12).font('Helvetica')
      .fillColor('#B8965A')
      .text(`Week ${weekNo} Program`, { align: 'center' });

    if (clientName) {
      doc.fontSize(10).fillColor('#6B6B6B')
        .text(`Prepared for: ${clientName}`, { align: 'center' });
    }

    doc.moveDown(1);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#E8E3DC').stroke();
    doc.moveDown(1);

    doc.fontSize(18).font('Helvetica-Bold')
      .fillColor('#2C2C2C')
      .text('WORKOUT PLAN');
    doc.moveDown(0.5);

    if (workoutPlan && workoutPlan.days) {
      for (const day of workoutPlan.days) {
        doc.fontSize(13).font('Helvetica-Bold')
          .fillColor('#B8965A')
          .text(day.name || day.day);
        doc.moveDown(0.3);

        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.fontSize(10).font('Helvetica')
              .fillColor('#2C2C2C')
              .text(`  ${ex.name}  —  ${ex.sets || ''}x${ex.reps || ''} ${ex.rest ? '(Rest: ' + ex.rest + ')' : ''}`, { indent: 20 });
            if (ex.notes) {
              doc.fontSize(9).fillColor('#6B6B6B')
                .text(`    ${ex.notes}`, { indent: 30 });
            }
          }
        }
        doc.moveDown(0.5);
      }
    } else if (typeof workoutPlan === 'string') {
      doc.fontSize(10).font('Helvetica').fillColor('#2C2C2C').text(workoutPlan);
    }

    doc.addPage();

    doc.fontSize(18).font('Helvetica-Bold')
      .fillColor('#2C2C2C')
      .text('NUTRITION PLAN');
    doc.moveDown(0.5);

    if (nutritionPlan && nutritionPlan.meals) {
      if (nutritionPlan.calories) {
        doc.fontSize(11).font('Helvetica-Bold').fillColor('#B8965A')
          .text(`Daily Target: ${nutritionPlan.calories} kcal | P: ${nutritionPlan.protein || '?'}g | C: ${nutritionPlan.carbs || '?'}g | F: ${nutritionPlan.fats || '?'}g`);
        doc.moveDown(0.5);
      }

      for (const meal of nutritionPlan.meals) {
        doc.fontSize(12).font('Helvetica-Bold')
          .fillColor('#2C2C2C')
          .text(meal.name || meal.meal);
        doc.moveDown(0.2);

        if (meal.items) {
          for (const item of meal.items) {
            doc.fontSize(10).font('Helvetica').fillColor('#6B6B6B')
              .text(`  • ${item}`, { indent: 20 });
          }
        }
        if (meal.notes) {
          doc.fontSize(9).fillColor('#B8965A')
            .text(`  ${meal.notes}`, { indent: 20 });
        }
        doc.moveDown(0.4);
      }
    } else if (typeof nutritionPlan === 'string') {
      doc.fontSize(10).font('Helvetica').fillColor('#2C2C2C').text(nutritionPlan);
    }

    doc.moveDown(2);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#E8E3DC').stroke();
    doc.moveDown(0.5);
    doc.fontSize(8).font('Helvetica').fillColor('#6B6B6B')
      .text('Generated by Fitness by Maddy Coaching System. For support, message +917082478374 on WhatsApp.', { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const authHeader = req.headers['authorization'];
  if (authHeader !== `Bearer ${process.env.INTERNAL_API_KEY}`) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  try {
    const { client_id, week_no } = req.body;
    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'client_id and week_no required' });
    }

    const db = getSupabase();

    const { data: client } = await db
      .from('clients')
      .select('*, lead:leads(*)')
      .eq('id', client_id)
      .single();

    if (!client) {
      return res.status(404).json({ error: 'Client not found' });
    }

    const { data: intake } = await db
      .from('intake_forms')
      .select('*')
      .eq('lead_id', client.lead_id)
      .order('submitted_at', { ascending: false })
      .limit(1)
      .single();

    const { data: recentCheckins } = await db
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    const anthropic = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });

    const systemPrompt = `You are a certified fitness coach working for Fitness by Maddy, an elite online coaching brand. You design weekly workout and nutrition plans that are:
- Science-backed and safe
- Tailored to the client's goals, body, injuries, and preferences
- Progressive (building on previous weeks)
- Realistic and sustainable

CRITICAL RULES:
- Never prescribe extreme calorie deficits (minimum 1200 kcal for women, 1500 for men)
- Never recommend banned or dangerous substances
- Never promise unrealistic timelines
- If the client has injuries or medical conditions, adjust exercises accordingly
- Always include warm-up and cool-down notes

Output ONLY valid JSON with this structure:
{
  "workout_plan": {
    "days": [
      {
        "day": "Day 1",
        "name": "Upper Body Push",
        "exercises": [
          { "name": "Bench Press", "sets": "4", "reps": "8-10", "rest": "90s", "notes": "" }
        ]
      }
    ],
    "notes": "General notes for the week"
  },
  "nutrition_plan": {
    "calories": 2200,
    "protein": 180,
    "carbs": 220,
    "fats": 70,
    "meals": [
      {
        "meal": "Meal 1 - Breakfast",
        "name": "Breakfast",
        "items": ["4 egg whites + 1 whole egg", "1 cup oats with banana"],
        "notes": ""
      }
    ],
    "notes": "General nutrition notes"
  },
  "weekly_focus": "Brief note on this week's focus area"
}`;

    const checkinSummary = recentCheckins && recentCheckins.length > 0
      ? recentCheckins.map(c =>
          `Week ${c.week_no}: Weight ${c.weight || '?'}kg, Waist ${c.waist || '?'}cm, Compliance ${c.compliance_score || '?'}/10, Energy ${c.energy || '?'}/10, Issues: ${c.issues || 'none'}`
        ).join('\n')
      : 'No previous check-ins available.';

    const clientProfile = `
Client: ${client.name || 'Unknown'}
Program: ${client.program}
Week: ${week_no}
${intake ? `
Age: ${intake.age || '?'}
Gender: ${intake.gender || '?'}
Height: ${intake.height_cm || '?'}cm
Weight: ${intake.weight_kg || '?'}kg
Goal: ${intake.goal || '?'}
Injuries: ${intake.injuries || 'None'}
Medical Conditions: ${intake.medical_conditions || 'None'}
Diet Preference: ${intake.diet_preference || 'No preference'}
Meals per day: ${intake.meals_per_day || '?'}
Workout days: ${intake.workout_days_per_week || '?'}
Gym access: ${intake.gym_access ? 'Yes' : 'No'}
Schedule: ${intake.schedule_preference || 'Flexible'}
` : 'No intake form data available.'}

Recent Check-ins:
${checkinSummary}
`;

    const message = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      system: systemPrompt,
      messages: [{
        role: 'user',
        content: `Generate the Week ${week_no} program for this client:\n\n${clientProfile}`
      }]
    });

    const responseText = message.content[0].text;

    if (hasDangerousContent(responseText)) {
      await escalateToMaddy(
        'Risky content in generated program',
        client.phone,
        `Week ${week_no} program flagged for dangerous content. Review required.`
      );
      return res.status(200).json({ ok: false, reason: 'flagged_for_review' });
    }

    let parsed;
    try {
      const jsonMatch = responseText.match(/\{[\s\S]*\}/);
      parsed = JSON.parse(jsonMatch ? jsonMatch[0] : responseText);
    } catch (parseErr) {
      console.error('Failed to parse Claude response:', parseErr.message);
      return res.status(500).json({ error: 'Failed to parse program' });
    }

    const workoutPlan = parsed.workout_plan || {};
    const nutritionPlan = parsed.nutrition_plan || {};
    const weeklyFocus = parsed.weekly_focus || '';

    const pdfBuffer = await generatePDF(workoutPlan, nutritionPlan, client.name, week_no);

    const fileName = `week_${week_no}.pdf`;
    const storagePath = `clients/${client.id}/${fileName}`;

    const { error: uploadErr } = await db.storage
      .from('programs')
      .upload(storagePath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true
      });

    if (uploadErr) {
      console.error('PDF upload error:', uploadErr.message);
    }

    const { data: urlData } = db.storage.from('programs').getPublicUrl(storagePath);
    const pdfUrl = urlData ? urlData.publicUrl : null;

    const { error: progErr } = await db.from('programs').upsert({
      client_id,
      week_no: parseInt(week_no),
      generated_at: new Date().toISOString(),
      pdf_url: pdfUrl,
      workout_plan: workoutPlan,
      nutrition_plan: nutritionPlan,
      notes: weeklyFocus
    }, { onConflict: 'client_id,week_no' });

    if (progErr) {
      console.error('Program record error:', progErr.message);
    }

    if (pdfUrl) {
      const market = detectMarket(client.phone);
      const templateName = isHinglish(market)
        ? 'weekly_program_hinglish'
        : 'weekly_program_english';

      await sendTemplate(client.phone, templateName, [
        client.name || 'there',
        String(week_no),
        weeklyFocus || 'Keep pushing this week!',
        pdfUrl
      ], true);

      await db.from('programs').update({
        whatsapp_sent_at: new Date().toISOString()
      }).eq('client_id', client_id).eq('week_no', parseInt(week_no));
    }

    return res.status(200).json({
      ok: true,
      program_week: week_no,
      pdf_url: pdfUrl,
      focus: weeklyFocus
    });
  } catch (err) {
    console.error('Generate program error:', err.message);
    return res.status(500).json({ error: 'Internal server error' });
  }
};
