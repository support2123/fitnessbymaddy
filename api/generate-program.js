const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { getSupabase } = require('./lib/supabase');
const { sendTemplate } = require('./lib/whatsapp');

const RISKY_PATTERNS = [
  /under\s*800\s*cal/i,
  /under\s*1[,.]?000\s*cal/i,
  /clenbuterol/i,
  /dnp/i,
  /ephedra/i,
  /anabolic/i,
  /steroid/i,
  /lose\s*\d{2,}\s*kg\s*in\s*\d\s*week/i,
  /crash\s*diet/i,
  /water\s*fast\s*for\s*\d+\s*day/i
];

function hasDangerousContent(text) {
  return RISKY_PATTERNS.some(p => p.test(text));
}

async function generatePDF(workout, nutrition, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.rect(0, 0, doc.page.width, 100).fill('#2C2C2C');
    doc.fontSize(28).fillColor('#B8965A')
       .text('FITNESS BY MADDY', 50, 30, { align: 'center' });
    doc.fontSize(14).fillColor('#FFFFFF')
       .text(`Week ${weekNo} Program — ${clientName || 'Client'}`, 50, 65, { align: 'center' });

    doc.moveDown(3);

    // Workout section
    doc.fillColor('#2C2C2C').fontSize(20)
       .text('WORKOUT PLAN', 50);
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#B8965A').stroke();
    doc.moveDown(0.5);

    if (workout && workout.days) {
      for (const day of workout.days) {
        doc.fontSize(14).fillColor('#B8965A').text(day.name || 'Day');
        doc.moveDown(0.3);
        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.fontSize(11).fillColor('#2C2C2C')
               .text(`  ${ex.name}  —  ${ex.sets || '3'} x ${ex.reps || '10'}${ex.notes ? '  (' + ex.notes + ')' : ''}`, { indent: 15 });
          }
        }
        doc.moveDown(0.5);
      }
    } else {
      doc.fontSize(11).fillColor('#6B6B6B')
         .text(typeof workout === 'string' ? workout : JSON.stringify(workout, null, 2));
    }

    // Nutrition section
    doc.addPage();
    doc.rect(0, 0, doc.page.width, 60).fill('#2C2C2C');
    doc.fontSize(20).fillColor('#B8965A')
       .text('NUTRITION PLAN', 50, 20, { align: 'center' });

    doc.moveDown(3);

    if (nutrition && nutrition.meals) {
      for (const meal of nutrition.meals) {
        doc.fontSize(14).fillColor('#B8965A').text(meal.name || 'Meal');
        doc.moveDown(0.3);
        if (meal.items) {
          for (const item of meal.items) {
            doc.fontSize(11).fillColor('#2C2C2C').text(`  ${item}`, { indent: 15 });
          }
        }
        if (meal.macros) {
          doc.fontSize(10).fillColor('#6B6B6B').text(`  Macros: ${meal.macros}`, { indent: 15 });
        }
        doc.moveDown(0.5);
      }
    } else {
      doc.fontSize(11).fillColor('#6B6B6B')
         .text(typeof nutrition === 'string' ? nutrition : JSON.stringify(nutrition, null, 2));
    }

    // Footer
    doc.fontSize(9).fillColor('#C8B89A')
       .text('Generated by Fitness by Maddy — fitnessbymaddy.com', 50, doc.page.height - 40, { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });

  const authHeader = req.headers['authorization'];
  if (authHeader !== `Bearer ${process.env.INTERNAL_API_KEY}`) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  try {
    const { client_id, week_no } = req.body;
    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'Missing client_id or week_no' });
    }

    const db = getSupabase();

    const { data: client } = await db
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) return res.status(404).json({ error: 'Client not found' });

    // Get last 2 check-ins
    const { data: checkins } = await db
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    // Get intake data from messages
    const { data: intakeMsg } = await db
      .from('messages')
      .select('body')
      .eq('phone', client.phone)
      .eq('template_name', 'intake_form')
      .order('sent_at', { ascending: false })
      .limit(1)
      .single();

    let intakeData = {};
    if (intakeMsg?.body) {
      try {
        const jsonStr = intakeMsg.body.replace('[INTAKE FORM] ', '');
        intakeData = JSON.parse(jsonStr);
      } catch {}
    }

    const prompt = `You are a certified fitness program architect for "Fitness by Maddy", a premium online coaching brand.

Generate a detailed Week ${week_no} program for this client.

CLIENT PROFILE:
- Name: ${client.name || 'Client'}
- Program: ${client.program}
- Goal: ${intakeData.goal || 'general fitness'}
- Age: ${intakeData.age || 'unknown'}
- Gender: ${intakeData.gender || 'unknown'}
- Injuries/Conditions: ${intakeData.injuries || 'none reported'}
- Diet Preference: ${intakeData.diet_pref || 'no preference'}
- Schedule: ${intakeData.schedule || 'flexible'}
- Current Weight: ${intakeData.current_weight || 'unknown'}

RECENT CHECK-IN DATA:
${checkins && checkins.length > 0 ? checkins.map(c => `Week ${c.week_no}: Weight ${c.weight}kg, Waist ${c.waist}cm, Compliance ${c.compliance_score}/10, Energy ${c.energy}/10, Issues: ${c.issues || 'none'}`).join('\n') : 'No check-ins yet (Week 1)'}

OUTPUT FORMAT (strict JSON):
{
  "workout_plan": {
    "days": [
      {
        "name": "Day 1 — Upper Body Push",
        "exercises": [
          { "name": "Bench Press", "sets": "4", "reps": "8-10", "notes": "progressive overload" }
        ]
      }
    ],
    "rest_days": "Wednesday & Sunday",
    "cardio": "3x/week, 20 min LISS"
  },
  "nutrition_plan": {
    "daily_calories": 1800,
    "protein_g": 140,
    "carbs_g": 180,
    "fat_g": 60,
    "meals": [
      {
        "name": "Meal 1 — Breakfast",
        "items": ["4 egg whites + 1 whole egg scramble", "1 cup oats with berries"],
        "macros": "P: 35g C: 45g F: 12g"
      }
    ],
    "hydration": "3-4L water daily",
    "supplements": ["Whey isolate post-workout", "Creatine 5g daily"]
  },
  "notes": "Brief coaching note for the week"
}

RULES:
- Be specific with exercises, sets, reps, and rest periods
- Tailor nutrition to client's diet preference and local food availability
- Never recommend below 1200 calories for women or 1500 for men
- Never recommend banned substances or extreme protocols
- Progressive overload from previous weeks if check-in data available
- Keep it practical and sustainable`;

    const anthropic = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });
    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      messages: [{ role: 'user', content: prompt }]
    });

    const responseText = response.content[0].text;

    // Safety check
    if (hasDangerousContent(responseText)) {
      await db.from('escalations').insert({
        phone: client.phone,
        client_id,
        reason: 'Dangerous content detected in generated program',
        message_body: responseText.slice(0, 500)
      });
      return res.status(422).json({ error: 'Program flagged for review', reason: 'safety' });
    }

    // Parse the JSON from response
    let programData;
    try {
      const jsonMatch = responseText.match(/\{[\s\S]*\}/);
      programData = JSON.parse(jsonMatch[0]);
    } catch {
      programData = { workout_plan: responseText, nutrition_plan: '', notes: '' };
    }

    const workoutPlan = programData.workout_plan || {};
    const nutritionPlan = programData.nutrition_plan || {};
    const notes = programData.notes || '';

    // Generate PDF
    const pdfBuffer = await generatePDF(workoutPlan, nutritionPlan, client.name, week_no);

    // Upload to Supabase Storage
    const pdfPath = `clients/${client_id}/week_${week_no}.pdf`;
    const { error: uploadError } = await db.storage
      .from('programs')
      .upload(pdfPath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true
      });

    if (uploadError) {
      console.error('PDF upload error:', uploadError.message);
    }

    const { data: urlData } = db.storage.from('programs').getPublicUrl(pdfPath);
    const pdfUrl = urlData?.publicUrl || pdfPath;

    // Save to programs table (audit trail)
    await db.from('programs').insert({
      client_id,
      week_no: parseInt(week_no),
      pdf_url: pdfUrl,
      workout_plan: workoutPlan,
      nutrition_plan: nutritionPlan,
      notes
    });

    // Send via WhatsApp
    await sendTemplate(client.phone, 'weekly_program', [
      client.name || 'there',
      String(week_no),
      notes.slice(0, 200) || 'Your new program is ready!'
    ]);

    // Update whatsapp_sent_at
    await db.from('programs')
      .update({ whatsapp_sent_at: new Date().toISOString() })
      .eq('client_id', client_id)
      .eq('week_no', parseInt(week_no));

    return res.json({ ok: true, pdf_url: pdfUrl });
  } catch (err) {
    console.error('Generate program error:', err.message);
    return res.status(500).json({ error: 'Program generation failed' });
  }
};
