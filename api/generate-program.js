const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { supabase } = require('./_lib/supabase');
const { sendText } = require('./_lib/whatsapp');
const { maskPhone } = require('./_lib/pii');

const RISKY_PATTERNS = [
  /under\s*1[0-2]00\s*cal/i,
  /starvation/i,
  /banned\s*substance/i,
  /steroid/i,
  /clenbuterol/i,
  /dnp/i,
  /extreme\s*cut/i,
  /lose\s*\d{2,}\s*(kg|lbs?)\s*(in|per)\s*(a\s*)?week/i,
];

function checkForRiskyContent(plan) {
  const text = JSON.stringify(plan);
  return RISKY_PATTERNS.some(p => p.test(text));
}

async function generatePDF(workout, nutrition, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.rect(0, 0, 595, 100).fill('#2C2C2C');
    doc.fontSize(28).fillColor('#B8965A').text('FITNESS BY MADDY', 50, 30);
    doc.fontSize(14).fillColor('#FFFFFF').text(`Week ${weekNo} Program — ${clientName}`, 50, 65);

    doc.moveDown(3);

    // Workout section
    doc.fontSize(20).fillColor('#2C2C2C').text('WORKOUT PLAN', 50);
    doc.moveDown(0.5);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#B8965A').lineWidth(2).stroke();
    doc.moveDown(0.5);

    if (workout && workout.days) {
      for (const day of workout.days) {
        doc.fontSize(14).fillColor('#B8965A').text(day.name || day.day, 50);
        doc.moveDown(0.3);
        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.fontSize(11).fillColor('#2C2C2C')
              .text(`  → ${ex.name}: ${ex.sets || ''}x${ex.reps || ''} ${ex.rest ? '(Rest: ' + ex.rest + ')' : ''}`, 60);
          }
        }
        if (day.notes) {
          doc.fontSize(10).fillColor('#6B6B6B').text(`  Note: ${day.notes}`, 60);
        }
        doc.moveDown(0.5);
      }
    } else {
      doc.fontSize(11).fillColor('#2C2C2C').text(JSON.stringify(workout, null, 2), 50);
    }

    doc.addPage();

    // Nutrition section
    doc.rect(0, 0, 595, 60).fill('#2C2C2C');
    doc.fontSize(20).fillColor('#B8965A').text('NUTRITION PLAN', 50, 20);
    doc.moveDown(3);

    if (nutrition && nutrition.meals) {
      for (const meal of nutrition.meals) {
        doc.fontSize(14).fillColor('#B8965A').text(meal.name || meal.meal, 50);
        doc.moveDown(0.3);
        if (meal.items) {
          for (const item of meal.items) {
            doc.fontSize(11).fillColor('#2C2C2C').text(`  → ${item}`, 60);
          }
        }
        if (meal.macros) {
          doc.fontSize(10).fillColor('#6B6B6B').text(`  Macros: ${meal.macros}`, 60);
        }
        doc.moveDown(0.5);
      }
    } else {
      doc.fontSize(11).fillColor('#2C2C2C').text(JSON.stringify(nutrition, null, 2), 50);
    }

    // Footer
    doc.moveDown(2);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#E8E3DC').lineWidth(1).stroke();
    doc.moveDown(0.5);
    doc.fontSize(9).fillColor('#6B6B6B')
      .text('Generated by Fitness by Maddy coaching system. For personal use only.', 50, doc.y, { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  try {
    const { client_id, week_no } = req.body;

    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'client_id and week_no required' });
    }

    const { data: client } = await supabase
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) {
      return res.status(404).json({ error: 'Client not found' });
    }

    const { data: recentCheckins } = await supabase
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    const anthropic = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });

    const checkinContext = recentCheckins && recentCheckins.length > 0
      ? recentCheckins.map(c => `Week ${c.week_no}: weight=${c.weight}kg, waist=${c.waist}cm, compliance=${c.compliance_score}/10, energy=${c.energy}/10, issues: ${c.issues || 'none'}`).join('\n')
      : 'No previous check-ins (Week 1)';

    const prompt = `You are a NASM-certified fitness program architect for "Fitness by Maddy", an elite online coaching brand.

Generate a complete Week ${week_no} training and nutrition program for this client:

CLIENT PROFILE:
- Name: ${client.name}
- Program: ${client.program}
- Started: ${client.program_started_at}

RECENT CHECK-INS:
${checkinContext}

RULES:
- Never prescribe extreme calorie deficits (minimum 1400 cal for women, 1600 for men)
- Never mention banned substances or steroids
- Set realistic expectations (0.5-1kg fat loss per week max)
- Progressive overload principles
- Include rest days
- Consider any reported issues/injuries

Return a JSON object with this exact structure:
{
  "workout_plan": {
    "days": [
      {
        "day": "Day 1 - Upper Body Push",
        "exercises": [
          { "name": "Bench Press", "sets": "4", "reps": "8-10", "rest": "90s" }
        ],
        "notes": "Optional coaching note"
      }
    ],
    "weekly_notes": "Overall coaching context for the week"
  },
  "nutrition_plan": {
    "daily_calories": 2000,
    "macros": { "protein": "150g", "carbs": "200g", "fats": "65g" },
    "meals": [
      {
        "meal": "Meal 1 - Breakfast",
        "items": ["4 egg whites + 1 whole egg", "1 cup oats with berries"],
        "macros": "P: 35g C: 50g F: 10g"
      }
    ],
    "notes": "Hydration and supplement notes"
  },
  "coaching_note": "1-liner motivational or context note for WhatsApp message"
}

Return ONLY valid JSON, no markdown or explanation.`;

    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      messages: [{ role: 'user', content: prompt }],
    });

    const responseText = response.content[0].text;
    let programData;
    try {
      programData = JSON.parse(responseText);
    } catch {
      const jsonMatch = responseText.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        programData = JSON.parse(jsonMatch[0]);
      } else {
        throw new Error('Failed to parse Claude response as JSON');
      }
    }

    if (checkForRiskyContent(programData)) {
      await require('./_lib/whatsapp').notifyMaddy(
        'Program flagged for review',
        `Client: ${client.name} (${maskPhone(client.phone)})\nWeek: ${week_no}\nReason: Contains potentially risky content. Please review before sending.`
      );
      return res.status(200).json({
        success: false,
        flagged: true,
        message: 'Program flagged for Maddy review — contains potentially risky content',
      });
    }

    const pdfBuffer = await generatePDF(
      programData.workout_plan,
      programData.nutrition_plan,
      client.name,
      week_no
    );

    const filePath = `${client.folder_url || 'clients/' + client.id}/week_${week_no}.pdf`;
    const { error: uploadError } = await supabase.storage
      .from('programs')
      .upload(filePath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true,
      });

    if (uploadError) {
      console.error('[Program] Upload error:', uploadError.message);
    }

    const { data: publicUrl } = supabase.storage.from('programs').getPublicUrl(filePath);

    const { data: program, error: dbError } = await supabase
      .from('programs')
      .insert({
        client_id,
        week_no,
        pdf_url: publicUrl?.publicUrl || filePath,
        workout_plan: programData.workout_plan,
        nutrition_plan: programData.nutrition_plan,
        notes: programData.coaching_note || null,
      })
      .select()
      .single();

    if (dbError) throw dbError;

    const coachingNote = programData.coaching_note || `Week ${week_no} program is ready!`;
    await sendText(
      client.phone,
      `📋 ${coachingNote}\n\nYour Week ${week_no} program PDF has been generated. Check your program folder or download here:\n${publicUrl?.publicUrl || 'Contact support for access.'}`
    );

    await supabase
      .from('programs')
      .update({ whatsapp_sent_at: new Date().toISOString() })
      .eq('id', program.id);

    console.log(`[Program] Generated Week ${week_no} for ${maskPhone(client.phone)}`);

    return res.status(200).json({
      success: true,
      program_id: program.id,
      pdf_url: publicUrl?.publicUrl,
    });
  } catch (error) {
    console.error('[Program Error]', error.message);
    return res.status(500).json({ error: 'Failed to generate program' });
  }
};
