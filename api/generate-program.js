const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { getSupabase } = require('../lib/supabase');
const { sendWhatsApp, maskPhone } = require('../lib/whatsapp');
const { logMessage } = require('../lib/rate-limit');
const { escalateToMaddy } = require('../lib/escalation');

const SAFETY_FLAGS = [
  'below 1000 calories', 'under 800 calories', 'extreme deficit',
  'clenbuterol', 'dnp', 'ephedra', 'anavar', 'sarms', 'steroids',
  'lose 10kg in 1 week', 'lose 20 pounds in a week', 'crash diet',
  'water fasting for', 'zero carb for weeks'
];

function hasSafetyIssue(text) {
  if (!text) return false;
  const lower = text.toLowerCase();
  return SAFETY_FLAGS.some(flag => lower.includes(flag));
}

async function generatePDF(workout, nutrition, client, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 120).fill('#1a1a1a');
    doc.fontSize(28).fill('#B8965A').text('FITNESS BY MADDY', 50, 35, { align: 'center' });
    doc.fontSize(14).fill('#FFFFFF').text(`Week ${weekNo} Program`, 50, 72, { align: 'center' });
    doc.fontSize(10).fill('#888888').text(client.name || 'Client', 50, 95, { align: 'center' });

    doc.moveDown(4);

    doc.rect(50, doc.y, doc.page.width - 100, 1).fill('#B8965A');
    doc.moveDown(1);

    doc.fontSize(18).fill('#1a1a1a').text('WORKOUT PLAN');
    doc.moveDown(0.5);

    if (workout && typeof workout === 'object') {
      const days = Object.entries(workout);
      for (const [day, exercises] of days) {
        doc.fontSize(13).fill('#B8965A').text(day.toUpperCase());
        doc.moveDown(0.3);

        if (Array.isArray(exercises)) {
          for (const ex of exercises) {
            const line = typeof ex === 'string' ? ex : `${ex.name || ex.exercise} — ${ex.sets || ''}x${ex.reps || ''} ${ex.notes || ''}`;
            doc.fontSize(10).fill('#333333').text(`  ${line}`, { indent: 15 });
          }
        } else if (typeof exercises === 'string') {
          doc.fontSize(10).fill('#333333').text(`  ${exercises}`, { indent: 15 });
        }
        doc.moveDown(0.5);
      }
    } else if (typeof workout === 'string') {
      doc.fontSize(10).fill('#333333').text(workout);
    }

    if (doc.y > 650) doc.addPage();
    doc.moveDown(1);
    doc.rect(50, doc.y, doc.page.width - 100, 1).fill('#B8965A');
    doc.moveDown(1);

    doc.fontSize(18).fill('#1a1a1a').text('NUTRITION PLAN');
    doc.moveDown(0.5);

    if (nutrition && typeof nutrition === 'object') {
      if (nutrition.calories) {
        doc.fontSize(11).fill('#B8965A').text(`Daily Target: ${nutrition.calories} kcal`);
        doc.moveDown(0.3);
      }
      if (nutrition.macros) {
        doc.fontSize(10).fill('#333333').text(`Protein: ${nutrition.macros.protein || '-'}g | Carbs: ${nutrition.macros.carbs || '-'}g | Fat: ${nutrition.macros.fat || '-'}g`);
        doc.moveDown(0.5);
      }
      const meals = nutrition.meals || nutrition.meal_plan;
      if (Array.isArray(meals)) {
        for (const meal of meals) {
          if (typeof meal === 'string') {
            doc.fontSize(10).fill('#333333').text(`  ${meal}`, { indent: 15 });
          } else {
            doc.fontSize(11).fill('#B8965A').text(meal.name || meal.meal || 'Meal');
            doc.fontSize(10).fill('#333333').text(`  ${meal.items || meal.description || ''}`, { indent: 15 });
            doc.moveDown(0.3);
          }
        }
      }
      if (nutrition.notes) {
        doc.moveDown(0.5);
        doc.fontSize(10).fill('#666666').text(`Note: ${nutrition.notes}`);
      }
    } else if (typeof nutrition === 'string') {
      doc.fontSize(10).fill('#333333').text(nutrition);
    }

    doc.moveDown(2);
    doc.rect(50, doc.y, doc.page.width - 100, 1).fill('#E8E3DC');
    doc.moveDown(0.5);
    doc.fontSize(8).fill('#999999').text('Generated by Fitness by Maddy Coaching System', { align: 'center' });
    doc.fontSize(8).text(`Week ${weekNo} — ${new Date().toLocaleDateString('en-GB')}`, { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const authHeader = req.headers['authorization'];
  if (authHeader !== `Bearer ${process.env.INTERNAL_API_KEY}`) {
    return res.status(401).json({ error: 'Unauthorized' });
  }

  const { client_id, week_no } = req.body;
  if (!client_id || !week_no) {
    return res.status(400).json({ error: 'client_id and week_no required' });
  }

  const supabase = getSupabase();

  const { data: client } = await supabase
    .from('clients')
    .select('*')
    .eq('id', client_id)
    .single();

  if (!client) return res.status(404).json({ error: 'Client not found' });

  const { data: checkins } = await supabase
    .from('checkins')
    .select('*')
    .eq('client_id', client_id)
    .order('week_no', { ascending: false })
    .limit(2);

  const { data: intake } = await supabase
    .from('intake_forms')
    .select('*')
    .eq('lead_id', client.lead_id)
    .limit(1)
    .single();

  const clientContext = {
    name: client.name,
    program: client.program,
    week: week_no,
    startDate: client.program_started_at,
    recentCheckins: checkins || [],
    intake: intake || {},
    goal: intake?.goal || 'general fitness',
    injuries: intake?.injuries || 'none reported',
    dietPreference: intake?.diet_preference || 'no preference',
    workoutLocation: intake?.workout_location || 'gym',
    currentWeight: checkins?.[0]?.weight || intake?.current_weight,
    targetWeight: intake?.target_weight
  };

  const anthropic = new Anthropic();

  let response;
  try {
    response = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      system: `You are a NASM-certified fitness program architect for Fitness by Maddy.
Generate safe, evidence-based, personalised weekly programs.
Output strict JSON with two keys: "workout_plan" and "nutrition_plan".
workout_plan: object with day names as keys, each containing an array of exercise objects {name, sets, reps, notes}.
nutrition_plan: object with {calories, macros: {protein, carbs, fat}, meals: [{name, items}], notes}.
Never recommend extreme calorie deficits (<1200 for women, <1500 for men).
Never recommend banned substances or unrealistic timelines.
Be specific with sets, reps, and food quantities.`,
      messages: [{
        role: 'user',
        content: `Generate Week ${week_no} program for this client:\n${JSON.stringify(clientContext, null, 2)}`
      }]
    });
  } catch (err) {
    console.error('Claude API error:', err.message);
    return res.status(502).json({ error: 'AI generation failed' });
  }

  let programData;
  try {
    const text = response.content[0].text;
    const jsonMatch = text.match(/\{[\s\S]*\}/);
    programData = JSON.parse(jsonMatch[0]);
  } catch {
    console.error('Failed to parse Claude response as JSON');
    return res.status(500).json({ error: 'Failed to parse generated program' });
  }

  const fullText = JSON.stringify(programData);
  if (hasSafetyIssue(fullText)) {
    await escalateToMaddy('Safety flag in generated program', {
      phone: client.phone,
      name: client.name,
      message: `Week ${week_no} program flagged for safety review`
    });
    return res.status(200).json({ flagged: true, reason: 'Safety review required' });
  }

  const pdfBuffer = await generatePDF(
    programData.workout_plan,
    programData.nutrition_plan,
    client,
    week_no
  );

  const pdfPath = `clients/${client_id}/week_${week_no}.pdf`;
  const { error: uploadError } = await supabase.storage
    .from('programs')
    .upload(pdfPath, pdfBuffer, {
      contentType: 'application/pdf',
      upsert: true
    });

  if (uploadError) {
    console.error('PDF upload failed:', uploadError.message);
    return res.status(500).json({ error: 'PDF upload failed' });
  }

  const { data: urlData } = supabase.storage.from('programs').getPublicUrl(pdfPath);
  const pdfUrl = urlData?.publicUrl || '';

  await supabase.from('programs').insert({
    client_id,
    week_no: parseInt(week_no),
    generated_at: new Date().toISOString(),
    pdf_url: pdfUrl,
    workout_plan: programData.workout_plan,
    nutrition_plan: programData.nutrition_plan,
    notes: `Auto-generated for ${client.name}, Week ${week_no}`
  });

  await sendWhatsApp(client.phone, 'weekly_program', {
    name: client.name || 'there',
    templateParams: [client.name || 'there', String(week_no)],
    media: { url: pdfUrl, filename: `Week_${week_no}_Program.pdf` }
  });
  await logMessage(client.phone, 'out', `Week ${week_no} program sent`, 'weekly_program');

  await supabase.from('programs')
    .update({ whatsapp_sent_at: new Date().toISOString() })
    .eq('client_id', client_id)
    .eq('week_no', week_no);

  console.log(`Program generated: ${maskPhone(client.phone)} Week ${week_no}`);
  return res.status(200).json({ success: true, pdfUrl });
};
