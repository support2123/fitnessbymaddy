const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');
const { supabase } = require('../lib/supabase');
const { sendTemplate } = require('../lib/whatsapp');
const { escalateToMaddy } = require('../lib/escalation');

const RISKY_PATTERNS = [
  /under\s*(800|700|600|500|400)\s*cal/i,
  /starvation/i,
  /clenbuterol|dnp|ephedra|sibutramine/i,
  /lose\s*\d{2,}\s*(kg|lbs?)\s*in\s*(1|one)\s*week/i,
];

function hasSafetyIssues(text) {
  return RISKY_PATTERNS.some(p => p.test(text));
}

async function generatePDF(workout, nutrition, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 100).fill('#2C2C2C');
    doc.fontSize(28).fillColor('#B8965A')
      .text('FITNESS BY MADDY', 50, 30, { align: 'center' });
    doc.fontSize(14).fillColor('#FFFFFF')
      .text(`Week ${weekNo} Program — ${clientName || 'Client'}`, 50, 65, { align: 'center' });

    doc.moveDown(3);
    doc.fillColor('#2C2C2C');

    doc.fontSize(20).fillColor('#B8965A').text('WORKOUT PLAN', 50);
    doc.moveDown(0.5);
    doc.fontSize(11).fillColor('#2C2C2C');

    if (typeof workout === 'object' && workout !== null) {
      const days = Object.keys(workout);
      for (const day of days) {
        doc.moveDown(0.5);
        doc.fontSize(13).fillColor('#B8965A').text(day.toUpperCase());
        doc.fontSize(10).fillColor('#2C2C2C');
        const exercises = Array.isArray(workout[day]) ? workout[day] : [workout[day]];
        for (const ex of exercises) {
          if (typeof ex === 'string') {
            doc.text(`  • ${ex}`);
          } else if (ex && ex.name) {
            doc.text(`  • ${ex.name} — ${ex.sets || '3'}x${ex.reps || '10'} ${ex.notes || ''}`);
          }
        }
      }
    } else {
      doc.text(String(workout || 'See attached plan'));
    }

    doc.addPage();
    doc.rect(0, 0, doc.page.width, 60).fill('#2C2C2C');
    doc.fontSize(20).fillColor('#B8965A').text('NUTRITION PLAN', 50, 20, { align: 'center' });

    doc.moveDown(3);
    doc.fillColor('#2C2C2C');
    doc.fontSize(11);

    if (typeof nutrition === 'object' && nutrition !== null) {
      const meals = Object.keys(nutrition);
      for (const meal of meals) {
        doc.moveDown(0.5);
        doc.fontSize(13).fillColor('#B8965A').text(meal.toUpperCase());
        doc.fontSize(10).fillColor('#2C2C2C');
        const items = Array.isArray(nutrition[meal]) ? nutrition[meal] : [nutrition[meal]];
        for (const item of items) {
          doc.text(`  • ${typeof item === 'string' ? item : JSON.stringify(item)}`);
        }
      }
    } else {
      doc.text(String(nutrition || 'See attached plan'));
    }

    doc.moveDown(2);
    doc.fontSize(9).fillColor('#999999')
      .text('Generated by Fitness by Maddy coaching system. For personal use only.', 50, doc.page.height - 60, { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  try {
    const { client_id, week_no } = req.body;

    if (!client_id || !week_no) {
      return res.status(400).json({ error: 'client_id and week_no are required' });
    }

    const { data: client } = await supabase
      .from('clients')
      .select('*')
      .eq('id', client_id)
      .single();

    if (!client) {
      return res.status(404).json({ error: 'Client not found' });
    }

    const { data: recentCheckins } = await supabase
      .from('checkins')
      .select('*')
      .eq('client_id', client_id)
      .order('week_no', { ascending: false })
      .limit(2);

    const { data: leadData } = client.lead_id
      ? await supabase.from('leads').select('first_msg').eq('id', client.lead_id).single()
      : { data: null };

    let intakeInfo = '';
    if (leadData?.first_msg) {
      try {
        const parsed = JSON.parse(leadData.first_msg);
        intakeInfo = `Goal: ${parsed.goal || 'General fitness'}, Injuries: ${parsed.injuries || 'None'}, Diet: ${parsed.diet_preference || 'No preference'}, Experience: ${parsed.experience_level || 'Intermediate'}`;
      } catch {
        intakeInfo = leadData.first_msg;
      }
    }

    const checkinSummary = (recentCheckins || []).map(c =>
      `Week ${c.week_no}: Weight ${c.weight || '?'}kg, Waist ${c.waist || '?'}cm, Compliance ${c.compliance_score || '?'}/10, Energy ${c.energy || '?'}/10, Issues: ${c.issues || 'None'}`
    ).join('\n');

    const anthropic = new Anthropic();

    const prompt = `You are a certified fitness coach creating a personalized weekly program. Output valid JSON only.

Client: ${client.name || 'Client'}
Program: ${client.program}
Week: ${week_no}
${intakeInfo ? `Profile: ${intakeInfo}` : ''}
${checkinSummary ? `Recent check-ins:\n${checkinSummary}` : 'No previous check-ins.'}

Create a week ${week_no} program with:
1. A workout plan (5-6 days, with exercises, sets, reps, rest times)
2. A nutrition plan (4-5 meals per day with portions)

Respond ONLY with JSON in this exact format:
{
  "workout_plan": {
    "Day 1 - Push": [{"name": "Exercise", "sets": "3", "reps": "10", "notes": "60s rest"}],
    "Day 2 - Pull": [...]
  },
  "nutrition_plan": {
    "Meal 1 - Breakfast": ["Item 1 (portion)", "Item 2 (portion)"],
    "Meal 2 - Snack": [...]
  },
  "notes": "Brief coaching note for the week"
}

Rules:
- Be realistic and evidence-based
- No extreme calorie deficits (minimum 1200 cal for women, 1500 for men)
- No banned substances
- Progressive overload from previous weeks if check-in data available
- Adjust based on compliance and energy scores`;

    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-20250514',
      max_tokens: 4000,
      messages: [{ role: 'user', content: prompt }],
    });

    const aiText = response.content[0].text;

    if (hasSafetyIssues(aiText)) {
      await escalateToMaddy(
        `Week ${week_no} program flagged for safety review`,
        client
      );
      return res.status(200).json({
        success: false,
        reason: 'Program flagged for safety review by Maddy',
      });
    }

    let parsed;
    try {
      const jsonMatch = aiText.match(/\{[\s\S]*\}/);
      parsed = JSON.parse(jsonMatch ? jsonMatch[0] : aiText);
    } catch {
      console.error('Failed to parse AI response');
      return res.status(500).json({ error: 'AI response was not valid JSON' });
    }

    const { workout_plan, nutrition_plan, notes } = parsed;

    const pdfBuffer = await generatePDF(
      workout_plan,
      nutrition_plan,
      client.name,
      week_no
    );

    const pdfPath = `clients/${client_id}/week_${week_no}.pdf`;
    const { error: uploadErr } = await supabase.storage
      .from('client-files')
      .upload(pdfPath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true,
      });

    if (uploadErr) {
      console.error('PDF upload error:', uploadErr.message);
    }

    const { data: urlData } = supabase.storage
      .from('client-files')
      .getPublicUrl(pdfPath);

    const pdfUrl = urlData?.publicUrl || pdfPath;

    const { data: program } = await supabase
      .from('programs')
      .insert({
        client_id,
        week_no,
        pdf_url: pdfUrl,
        workout_plan,
        nutrition_plan,
        notes: notes || null,
      })
      .select()
      .single();

    await sendTemplate(client.phone, 'weekly_program', [
      client.name || 'there',
      `${week_no}`,
      pdfUrl,
    ]);

    await supabase
      .from('programs')
      .update({ whatsapp_sent_at: new Date().toISOString() })
      .eq('id', program.id);

    return res.status(200).json({
      success: true,
      program_id: program.id,
      pdf_url: pdfUrl,
    });
  } catch (err) {
    console.error('Generate program error:', err.message);
    return res.status(500).json({ error: 'Internal server error' });
  }
};
