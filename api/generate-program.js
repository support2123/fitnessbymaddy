const { getSupabase } = require('./_lib/supabase');
const { sendTemplate, maskPhone } = require('./_lib/whatsapp');
const { cors, programLabel } = require('./_lib/helpers');
const Anthropic = require('@anthropic-ai/sdk');
const PDFDocument = require('pdfkit');

const SAFETY_FLAGS = [
  'extreme calorie', 'below 1000 cal', 'starvation',
  'banned substance', 'steroid', 'sarm', 'clenbuterol',
  'lose 10kg in 1 week', 'crash diet'
];

function hasSafetyIssue(text) {
  const lower = (text || '').toLowerCase();
  return SAFETY_FLAGS.some(flag => lower.includes(flag));
}

async function generatePDF(workout, nutrition, clientName, weekNo) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.rect(0, 0, doc.page.width, 100).fill('#2C2C2C');
    doc.fontSize(28).fill('#B8965A').text('FITNESS BY MADDY', 50, 30);
    doc.fontSize(12).fill('#FFFFFF').text(`Week ${weekNo} Program — ${clientName || 'Client'}`, 50, 65);

    doc.moveDown(3);
    doc.fill('#2C2C2C');

    doc.fontSize(20).fill('#B8965A').text('WORKOUT PLAN', 50);
    doc.moveDown(0.5);
    doc.fontSize(11).fill('#2C2C2C');

    if (workout && workout.days) {
      for (const day of workout.days) {
        doc.moveDown(0.3);
        doc.fontSize(13).fill('#2C2C2C').text(day.name || 'Day', { underline: true });
        doc.fontSize(10).fill('#6B6B6B');
        if (day.exercises) {
          for (const ex of day.exercises) {
            doc.text(`  → ${ex.name}: ${ex.sets || '3'} x ${ex.reps || '10'} ${ex.notes || ''}`, { indent: 20 });
          }
        }
      }
    } else {
      doc.text(JSON.stringify(workout, null, 2).slice(0, 2000));
    }

    doc.addPage();
    doc.rect(0, 0, doc.page.width, 60).fill('#2C2C2C');
    doc.fontSize(20).fill('#B8965A').text('NUTRITION PLAN', 50, 20);

    doc.moveDown(2);
    doc.fill('#2C2C2C');
    doc.fontSize(11);

    if (nutrition && nutrition.daily_calories) {
      doc.fontSize(13).text(`Daily Calories: ${nutrition.daily_calories} kcal`);
      doc.fontSize(11).fill('#6B6B6B');
      if (nutrition.macros) {
        doc.text(`Protein: ${nutrition.macros.protein}g | Carbs: ${nutrition.macros.carbs}g | Fat: ${nutrition.macros.fat}g`);
      }
      doc.moveDown(0.5);
      if (nutrition.meals) {
        for (const meal of nutrition.meals) {
          doc.moveDown(0.3);
          doc.fontSize(12).fill('#2C2C2C').text(meal.name || 'Meal', { underline: true });
          doc.fontSize(10).fill('#6B6B6B');
          if (meal.items) {
            for (const item of meal.items) {
              doc.text(`  → ${item}`, { indent: 20 });
            }
          }
        }
      }
    } else {
      doc.text(JSON.stringify(nutrition, null, 2).slice(0, 2000));
    }

    doc.moveDown(2);
    doc.fontSize(9).fill('#C8B89A').text('Generated by FitnessByMaddy Automation — Not a substitute for medical advice.', { align: 'center' });

    doc.end();
  });
}

module.exports = async function handler(req, res) {
  if (cors(req, res)) return;
  if (req.method !== 'POST') return res.status(405).json({ error: 'POST only' });

  const db = getSupabase();
  const { client_id, week_no } = req.body || {};

  if (!client_id || !week_no) {
    return res.status(400).json({ error: 'missing client_id or week_no' });
  }

  const { data: client } = await db
    .from('clients')
    .select('*')
    .eq('id', client_id)
    .single();

  if (!client) return res.status(404).json({ error: 'client_not_found' });

  const { data: checkins } = await db
    .from('checkins')
    .select('*')
    .eq('client_id', client_id)
    .order('week_no', { ascending: false })
    .limit(2);

  const { data: intake } = await db
    .from('intake_data')
    .select('*')
    .eq('lead_id', client.lead_id)
    .single();

  const anthropic = new Anthropic({ apiKey: process.env.CLAUDE_API_KEY });

  const systemPrompt = `You are a certified fitness program architect for FitnessByMaddy.
Generate a JSON training + nutrition plan for one week.

RULES:
- Safe, evidence-based programming only
- Never go below 1200 calories for women or 1500 for men
- No banned substances or supplements
- Progressive overload week-to-week
- Consider injuries, preferences, compliance history

Return ONLY valid JSON with this structure:
{
  "workout_plan": {
    "days": [
      {
        "name": "Day 1 - Upper Body",
        "exercises": [
          { "name": "Bench Press", "sets": "4", "reps": "8-10", "notes": "2 min rest" }
        ]
      }
    ],
    "notes": "..."
  },
  "nutrition_plan": {
    "daily_calories": 2000,
    "macros": { "protein": 150, "carbs": 200, "fat": 65 },
    "meals": [
      { "name": "Meal 1 - Breakfast", "items": ["3 eggs scrambled", "2 toast", "1 banana"] }
    ],
    "notes": "..."
  },
  "weekly_note": "Short motivational note for the client"
}`;

  const userMsg = `Client: ${client.name || 'Unknown'}
Program: ${programLabel(client.program)}
Week: ${week_no}
Goal: ${intake?.goal || 'general fitness'}
Age: ${intake?.age || 'unknown'}
Gender: ${intake?.gender || 'unknown'}
Height: ${intake?.height_cm || 'unknown'} cm
Weight: ${checkins?.[0]?.weight || intake?.weight_kg || 'unknown'} kg
Injuries: ${intake?.injuries || 'none reported'}
Diet preference: ${intake?.diet_pref || 'no preference'}
Schedule: ${intake?.schedule || 'flexible'}
Experience: ${intake?.experience || 'intermediate'}

Recent check-ins:
${checkins?.map(c => `  Week ${c.week_no}: weight=${c.weight}kg, compliance=${c.compliance_score}/10, energy=${c.energy}/10, issues="${c.issues || 'none'}"`).join('\n') || '  No previous check-ins'}

Generate Week ${week_no} program.`;

  let generated;
  try {
    const response = await anthropic.messages.create({
      model: 'claude-sonnet-4-6',
      max_tokens: 4000,
      system: systemPrompt,
      messages: [{ role: 'user', content: userMsg }]
    });

    const raw = response.content[0].text;
    const jsonMatch = raw.match(/\{[\s\S]*\}/);
    if (!jsonMatch) throw new Error('No JSON in response');
    generated = JSON.parse(jsonMatch[0]);
  } catch (err) {
    console.error('[GenProgram] Claude API error:', err.message);
    return res.status(500).json({ error: 'generation_failed' });
  }

  const fullText = JSON.stringify(generated);
  if (hasSafetyIssue(fullText)) {
    const { escalateToMaddy } = require('./_lib/escalation');
    await escalateToMaddy('unsafe_program_flagged', client.phone, `Week ${week_no} program flagged for safety review`);
    return res.status(422).json({ error: 'safety_review_needed', week_no });
  }

  let pdfUrl = null;
  try {
    const pdfBuffer = await generatePDF(
      generated.workout_plan,
      generated.nutrition_plan,
      client.name,
      week_no
    );

    const filePath = `${client.id}/week_${week_no}.pdf`;
    const { error: uploadErr } = await db.storage
      .from('clients')
      .upload(filePath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true
      });

    if (uploadErr) {
      console.error('[GenProgram] PDF upload error:', uploadErr.message);
    } else {
      const { data: urlData } = db.storage.from('clients').getPublicUrl(filePath);
      pdfUrl = urlData?.publicUrl || null;
    }
  } catch (err) {
    console.error('[GenProgram] PDF generation error:', err.message);
  }

  const { error: dbErr } = await db.from('programs').upsert({
    client_id,
    week_no,
    workout_plan: generated.workout_plan,
    nutrition_plan: generated.nutrition_plan,
    notes: generated.weekly_note || '',
    pdf_url: pdfUrl,
    generated_at: new Date().toISOString()
  }, { onConflict: 'client_id,week_no' });

  if (dbErr) {
    console.error('[GenProgram] DB save error:', dbErr.message);
  }

  if (pdfUrl) {
    await sendTemplate(client.phone, 'weekly_program', [
      client.name || 'there',
      `${week_no}`,
      generated.weekly_note || 'New program ready — let\'s go!',
      pdfUrl
    ]);

    await db.from('programs').update({
      whatsapp_sent_at: new Date().toISOString()
    }).eq('client_id', client_id).eq('week_no', week_no);
  }

  return res.json({
    ok: true,
    week_no,
    pdf_url: pdfUrl,
    workout_plan: generated.workout_plan,
    nutrition_plan: generated.nutrition_plan
  });
};
